export function kickoff(ref: PlanRef, body: string): string {
  return `规划已结束。用户已批准下列固定版本，请执行并验证。
先读取批准文件：${ref.path}
SHA-256：${ref.hash}
下面的全文是本次批准内容；不要跟随草稿后续修改。源文件或资料需按需重新读取。
保持现有项目规则和权限。可调整方法；范围、验收标准或关键假设变化时先暂停确认。
逐项报告预期、实际和证据。验证做不到就标为未验证。不要自行降低标准。

${body}`;
}
